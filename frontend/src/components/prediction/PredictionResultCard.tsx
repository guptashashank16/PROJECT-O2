import React from 'react';
import {
  Cpu,
  HelpCircle,
  Sparkles,
  UserCheck,
} from 'lucide-react';
import { useAppState } from '../../context/AppStateContext';
import { getRiskBadgeColor } from '../../utils/formatters';
import { WhatIfLabCard } from './WhatIfLabCard';

export const PredictionResultCard: React.FC = () => {
  const { patientPrediction } = useAppState();

  if (!patientPrediction) return null;

  const badgeStyle = getRiskBadgeColor(patientPrediction.risk_level);
  const isPositive = patientPrediction.predicted_class === '1';

  // Extract base features for What-If
  const baseFeatures: Record<string, any> = {};
  if (patientPrediction.feature_values && patientPrediction.feature_values.length > 0) {
    patientPrediction.feature_values.forEach((fv) => {
      baseFeatures[fv.feature_name] = fv.raw_input_value ?? fv.raw_value ?? fv.transformed_value;
    });
  } else if (patientPrediction.feature_attributions) {
    patientPrediction.feature_attributions.forEach((fa) => {
      baseFeatures[fa.feature_name] = fa.input_value ?? fa.raw_input_value ?? fa.value;
    });
  }

  return (
    <div className="space-y-6">
      <div className="glass-panel-pink rounded-3xl p-6 space-y-6 border border-pink-300 shadow-xl animate-in fade-in duration-300">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-pink-200 pb-4">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-pink-500 text-white flex items-center justify-center shadow-md shadow-pink-500/20">
              <UserCheck className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-slate-900">Diagnostic Inference Output</h3>
              <p className="text-xs text-slate-500">
                Generated by <strong className="text-pink-700">{patientPrediction.model_name}</strong> ({patientPrediction.model_type})
              </p>
            </div>
          </div>

          <div
            className={`px-3.5 py-1.5 rounded-xl border font-bold text-xs flex items-center gap-2 ${badgeStyle.bg} ${badgeStyle.text} ${badgeStyle.border}`}
          >
            <span className="w-2 h-2 rounded-full bg-current animate-pulse" />
            <span>{patientPrediction.risk_level}</span>
          </div>
        </div>

        {/* Main Prediction Metrics Grid */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {/* Predicted Class Label */}
          <div className="p-4 rounded-2xl bg-white/90 border border-pink-200 space-y-1">
            <span className="text-slate-600 text-xs font-bold block">Predicted Diagnosis</span>
            <div
              className={`text-xl font-bold font-mono ${
                isPositive ? 'text-rose-700' : 'text-emerald-700'
              }`}
            >
              {patientPrediction.predicted_label}
            </div>
            <div className="text-[11px] text-slate-500 font-medium">
              Binary Class Index: {patientPrediction.predicted_class}
            </div>
          </div>

          {/* Positive Probability */}
          <div className="p-4 rounded-2xl bg-white/90 border border-pink-200 space-y-1">
            <span className="text-slate-600 text-xs font-bold block">Positive Risk Probability</span>
            <div className="text-xl font-bold text-pink-700 font-mono">
              {(patientPrediction.probability_positive * 100).toFixed(1)}%
            </div>
            <div className="w-full h-2 bg-pink-100 rounded-full overflow-hidden mt-1">
              <div
                className="h-full bg-gradient-to-r from-pink-500 to-rose-600 rounded-full"
                style={{ width: `${patientPrediction.probability_positive * 100}%` }}
              />
            </div>
          </div>

          {/* Prediction Confidence */}
          <div className="p-4 rounded-2xl bg-white/90 border border-pink-200 space-y-1">
            <span className="text-slate-600 text-xs font-bold block">Model Decision Confidence</span>
            <div className="text-xl font-bold text-slate-900 font-mono">
              {patientPrediction.confidence.toFixed(1)}%
            </div>
            <div className="text-[11px] text-slate-500 font-medium">
              Negative Probability: {(patientPrediction.probability_negative * 100).toFixed(1)}%
            </div>
          </div>
        </div>

        {/* Quantum State Vector Display (if VQC) */}
        {patientPrediction.quantum_features_state && patientPrediction.quantum_features_state.length > 0 && (
          <div className="p-4 rounded-2xl bg-pink-50/80 border border-pink-200 space-y-2">
            <div className="flex items-center justify-between text-xs">
              <span className="font-bold text-pink-800 flex items-center gap-1.5">
                <Cpu className="w-3.5 h-3.5 text-pink-600" />
                Quantum Circuit Input State [0, π]
              </span>
              <span className="text-[10px] font-mono text-pink-700 font-bold">
                {patientPrediction.quantum_features_state.length} Qubits Bound
              </span>
            </div>

            <div className="grid grid-cols-3 sm:grid-cols-6 gap-2 pt-1 font-mono text-xs text-center">
              {patientPrediction.quantum_features_state.map((val, idx) => (
                <div key={idx} className="p-2 rounded-xl bg-white border border-pink-200">
                  <span className="text-[10px] text-slate-500 block font-medium">Qubit {idx}</span>
                  <span className="text-pink-700 font-bold">{val.toFixed(3)} rad</span>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Patient Clinical Feature Inputs */}
        {patientPrediction.feature_values && patientPrediction.feature_values.length > 0 && (
          <div className="space-y-3">
            <div className="flex items-center justify-between">
              <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wider flex items-center gap-2">
                <Sparkles className="w-3.5 h-3.5 text-pink-600" />
                Patient Feature Inputs (Normalized Model Values)
              </h4>
              <span className="text-[10px] text-slate-500 font-mono">
                {patientPrediction.feature_values.length} features fed to pipeline
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2.5">
              {patientPrediction.feature_values.map((val) => (
                <div
                  key={val.feature_name}
                  className="p-3 rounded-2xl bg-white/90 border border-pink-200 space-y-1"
                >
                  <div className="flex items-center justify-between text-xs">
                    <span className="font-bold text-slate-800 truncate max-w-[150px]" title={val.feature_name}>
                      {val.feature_name}
                    </span>
                    <span className="font-mono text-pink-700 font-bold">{String(val.raw_input_value ?? val.raw_value ?? val.transformed_value)}</span>
                  </div>
                  <div className="text-[10px] text-slate-500 font-medium">{val.description}</div>
                </div>
              ))}
            </div>

            <div className="p-3 rounded-xl bg-slate-50 border border-slate-200 text-[11px] text-slate-600 flex items-start gap-2">
              <HelpCircle className="w-3.5 h-3.5 text-slate-400 shrink-0 mt-0.5" />
              <span>{patientPrediction.interpretation_disclaimer || 'Feature values represent normalized model inputs and PCA projections. They do not constitute causal patient risk factor rankings.'}</span>
            </div>
          </div>
        )}
      </div>

      {/* What-If Sensitivity Lab */}
      {Object.keys(baseFeatures).length > 0 && (
        <WhatIfLabCard baseFeatures={baseFeatures} />
      )}
    </div>
  );
};
