import React from 'react';
import {
  Activity,
  AlertTriangle,
  CheckCircle2,
  Cpu,
  ShieldAlert,
  Sparkles,
  UserCheck,
} from 'lucide-react';
import { useAppState } from '../../context/AppStateContext';
import { getRiskBadgeColor } from '../../utils/formatters';

export const PredictionResultCard: React.FC = () => {
  const { patientPrediction } = useAppState();

  if (!patientPrediction) return null;

  const badgeStyle = getRiskBadgeColor(patientPrediction.risk_level);
  const isPositive = patientPrediction.predicted_class === '1';

  return (
    <div className="glass-panel rounded-2xl p-6 space-y-6 animate-in fade-in duration-300">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-800 pb-4">
        <div className="flex items-center gap-2.5">
          <div className="w-8 h-8 rounded-lg bg-emerald-500/10 text-emerald-400 flex items-center justify-center border border-emerald-500/20">
            <UserCheck className="w-4 h-4" />
          </div>
          <div>
            <h3 className="text-sm font-bold text-white">Diagnostic Prediction Result</h3>
            <p className="text-xs text-slate-400">
              Generated by <strong className="text-cyan-300">{patientPrediction.model_name}</strong> ({patientPrediction.model_type})
            </p>
          </div>
        </div>

        <div
          className={`px-3.5 py-1.5 rounded-xl border font-semibold text-xs flex items-center gap-2 ${badgeStyle.bg} ${badgeStyle.text} ${badgeStyle.border}`}
        >
          <span className="w-2 h-2 rounded-full bg-current animate-pulse" />
          <span>{patientPrediction.risk_level}</span>
        </div>
      </div>

      {/* Main Prediction Metrics Grid */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        {/* Predicted Class Label */}
        <div className="p-4 rounded-xl bg-slate-900/80 border border-slate-800 space-y-1">
          <span className="text-slate-400 text-xs font-medium block">Predicted Diagnosis</span>
          <div
            className={`text-xl font-bold font-mono ${
              isPositive ? 'text-rose-400' : 'text-emerald-400'
            }`}
          >
            {patientPrediction.predicted_label}
          </div>
          <div className="text-[11px] text-slate-500">
            Binary Class Index: {patientPrediction.predicted_class}
          </div>
        </div>

        {/* Positive Probability */}
        <div className="p-4 rounded-xl bg-slate-900/80 border border-slate-800 space-y-1">
          <span className="text-slate-400 text-xs font-medium block">Positive Risk Probability</span>
          <div className="text-xl font-bold text-cyan-400 font-mono">
            {(patientPrediction.probability_positive * 100).toFixed(1)}%
          </div>
          <div className="w-full h-1.5 bg-slate-950 rounded-full overflow-hidden mt-1">
            <div
              className="h-full bg-cyan-500 rounded-full"
              style={{ width: `${patientPrediction.probability_positive * 100}%` }}
            />
          </div>
        </div>

        {/* Prediction Confidence */}
        <div className="p-4 rounded-xl bg-slate-900/80 border border-slate-800 space-y-1">
          <span className="text-slate-400 text-xs font-medium block">Model Decision Confidence</span>
          <div className="text-xl font-bold text-white font-mono">
            {patientPrediction.confidence.toFixed(1)}%
          </div>
          <div className="text-[11px] text-slate-500">
            Negative Probability: {(patientPrediction.probability_negative * 100).toFixed(1)}%
          </div>
        </div>
      </div>

      {/* Quantum State Vector Display (if VQC) */}
      {patientPrediction.quantum_features_state && patientPrediction.quantum_features_state.length > 0 && (
        <div className="p-4 rounded-xl bg-cyan-500/5 border border-cyan-500/20 space-y-2">
          <div className="flex items-center justify-between text-xs">
            <span className="font-semibold text-cyan-300 flex items-center gap-1.5">
              <Cpu className="w-3.5 h-3.5 text-cyan-400" />
              Quantum Circuit Input State [0, π]
            </span>
            <span className="text-[10px] font-mono text-cyan-400">
              {patientPrediction.quantum_features_state.length} Qubits Bound
            </span>
          </div>

          <div className="grid grid-cols-3 sm:grid-cols-6 gap-2 pt-1 font-mono text-xs text-center">
            {patientPrediction.quantum_features_state.map((val, idx) => (
              <div key={idx} className="p-2 rounded-lg bg-slate-900 border border-slate-800">
                <span className="text-[10px] text-slate-500 block">Qubit {idx}</span>
                <span className="text-cyan-300 font-bold">{val.toFixed(3)} rad</span>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Patient-Specific Feature Attributions */}
      {patientPrediction.feature_attributions.length > 0 && (
        <div className="space-y-3">
          <h4 className="text-xs font-bold text-slate-300 uppercase tracking-wider flex items-center gap-2">
            <Sparkles className="w-3.5 h-3.5 text-purple-400" />
            Patient Clinical Feature Impact
          </h4>

          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2.5">
            {patientPrediction.feature_attributions.map((attr) => (
              <div
                key={attr.feature_name}
                className="p-3 rounded-xl bg-slate-900/60 border border-slate-800 space-y-1"
              >
                <div className="flex items-center justify-between text-xs">
                  <span className="font-semibold text-slate-200 truncate max-w-[150px]" title={attr.feature_name}>
                    {attr.feature_name}
                  </span>
                  <span className="font-mono text-slate-300 font-bold">{String(attr.input_value)}</span>
                </div>
                <div className="text-[10px] text-slate-400 font-mono">{attr.description}</div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
